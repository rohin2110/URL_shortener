-- URL shortener schema — equivalent to SQLAlchemy create_all() + init_db().
-- Paste into the Supabase SQL editor. Idempotent: safe to run more than once.

CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email           VARCHAR(320) NOT NULL,
    hashed_password VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS urls (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    short_code   VARCHAR(16),            -- NULL only inside the creating transaction
    original_url VARCHAR(2048) NOT NULL,
    owner_id     BIGINT NOT NULL,
    click_count  BIGINT DEFAULT 0 NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    is_active    BOOLEAN DEFAULT true NOT NULL,
    CONSTRAINT pk_urls PRIMARY KEY (id),
    CONSTRAINT fk_urls_owner_id_users FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_urls_short_code ON urls (short_code);
CREATE INDEX IF NOT EXISTS ix_urls_owner_id ON urls (owner_id);

CREATE TABLE IF NOT EXISTS clicks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    url_id     BIGINT NOT NULL,
    clicked_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    ip_hash    VARCHAR(64) NOT NULL,     -- HMAC-SHA256 of the IP, never the raw IP
    user_agent VARCHAR(512),
    referrer   VARCHAR(2048),
    CONSTRAINT pk_clicks PRIMARY KEY (id),
    CONSTRAINT fk_clicks_url_id_urls FOREIGN KEY (url_id) REFERENCES urls (id) ON DELETE CASCADE
);

-- (url_id, clicked_at) also serves as the url_id index (leading column).
CREATE INDEX IF NOT EXISTS ix_clicks_url_id_clicked_at ON clicks (url_id, clicked_at);
CREATE INDEX IF NOT EXISTS ix_clicks_clicked_at ON clicks (clicked_at);

-- Block Supabase's auto-generated REST API (anon/authenticated roles) from these
-- tables. No policies = no access. The app connects as the owner and bypasses RLS.
ALTER TABLE users  ENABLE ROW LEVEL SECURITY;
ALTER TABLE urls   ENABLE ROW LEVEL SECURITY;
ALTER TABLE clicks ENABLE ROW LEVEL SECURITY;
